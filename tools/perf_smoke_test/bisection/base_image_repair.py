"""Bounded Docker base-image repairs for the bisection probe."""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path

ALLOWED_APT_PACKAGES = frozenset(
    {
        # Needed by pytetwild/fTetWild builds in newer IsaacLab commits.
        "libgmp-dev",
    }
)

_APT_PACKAGE_RE = re.compile(r"^[a-z0-9][a-z0-9+.-]*$")


@dataclass(frozen=True)
class BaseImageRepair:
    """Description of a generated Docker repair image."""

    base_image: str
    repaired_image: str
    apt_packages: list[str]
    dockerfile: Path


def validate_apt_packages(packages: list[str]) -> list[str]:
    """Validate and normalize requested apt packages.

    Args:
        packages: Package names requested by the probe.

    Returns:
        Sorted, de-duplicated package names.

    Raises:
        ValueError: If a package is malformed or not allowlisted.
    """
    normalized = sorted({package.strip() for package in packages if package.strip()})
    if not normalized:
        raise ValueError("repair_base_image requires at least one apt package")
    for package in normalized:
        if not _APT_PACKAGE_RE.match(package):
            raise ValueError(f"invalid apt package name: {package!r}")
        if package not in ALLOWED_APT_PACKAGES:
            raise ValueError(f"apt package is not allowlisted for automated repair: {package}")
    return normalized


def repair_image_tag(base_image: str, packages: list[str]) -> str:
    """Return a stable local tag for a base-image repair."""
    payload = json.dumps({"base_image": base_image, "apt_packages": packages}, sort_keys=True)
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]
    return f"isaaclab-bisect:repair-{digest}"


def write_repair_dockerfile(base_image: str, packages: list[str], repair_dir: Path) -> BaseImageRepair:
    """Write a generated Dockerfile that installs validated apt packages."""
    if "\n" in base_image or "\r" in base_image or not base_image.strip():
        raise ValueError("base image must be a non-empty single-line Docker image reference")
    apt_packages = validate_apt_packages(packages)
    repaired_image = repair_image_tag(base_image, apt_packages)
    repair_dir.mkdir(parents=True, exist_ok=True)
    dockerfile = repair_dir / "Dockerfile"
    package_lines = " \\\n        ".join(apt_packages)
    dockerfile.write_text(
        "\n".join(
            [
                "# Generated by the IsaacLab bisection probe. Do not edit by hand.",
                f"FROM {base_image}",
                "",
                "ENV DEBIAN_FRONTEND=noninteractive",
                "RUN apt-get update && apt-get install -y --no-install-recommends \\",
                f"        {package_lines} \\",
                "    && rm -rf /var/lib/apt/lists/*",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return BaseImageRepair(base_image, repaired_image, apt_packages, dockerfile)


def docker_build_command(repair: BaseImageRepair) -> list[str]:
    """Return the Docker command that builds ``repair``."""
    return ["docker", "build", "-t", repair.repaired_image, str(repair.dockerfile.parent)]
